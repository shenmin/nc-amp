"""Build-time: convert the Audiowide glyphs used by the title ('nc-amp') into
flattened vector contours -> titleglyphs.inc (Pascal).  Audiowide (c) 2012 Astigmatic (AOETI),
SIL Open Font License 1.1 (see OFL-Audiowide.txt)."""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'Audiowide-Regular.ttf')
CHARS = 'nc-amp'
STEPS = 10
f = TTFont(SRC); gs = f.getGlyphSet(); cmap = f.getBestCmap()
class P(BasePen):
    def __init__(s, gs): super().__init__(gs); s.cs = []; s.cur = None
    def _moveTo(s, p): s.cur = [p]; s.cs.append(s.cur)
    def _lineTo(s, p): s.cur.append(p)
    def _qCurveToOne(s, c, p):
        x0, y0 = s.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS; u = 1 - t
            s.cur.append((u*u*x0 + 2*u*t*c[0] + t*t*p[0], u*u*y0 + 2*u*t*c[1] + t*t*p[1]))
    def _curveToOne(s, c1, c2, p):
        x0, y0 = s.cur[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS; u = 1 - t
            s.cur.append((u**3*x0 + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p[0],
                          u**3*y0 + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p[1]))
    def _closePath(s): pass
upm = f['head'].unitsPerEm
xb = None
pen = P(gs); gs[cmap[ord('x')]].draw(pen)
xh = max(y for c in pen.cs for _, y in c)
out = ['{ generated by assets/fonts/mkglyphs.py from Audiowide-Regular.ttf (SIL OFL 1.1) - do not edit }',
       'const', f'  TG_UPM = {upm};', f'  TG_XHEIGHT = {round(xh)};']
pts = []; cstart = []; gfirst = []; gcount = []; adv = []
for ch in CHARS:
    g = cmap[ord(ch)]; pen = P(gs); gs[g].draw(pen)
    adv.append(f['hmtx'][g][0]); gfirst.append(len(cstart)); gcount.append(len(pen.cs))
    for c in pen.cs:
        if len(c) > 1 and c[0] == c[-1]: c = c[:-1]
        cstart.append(len(pts)); pts += [(round(x, 1), round(y, 1)) for x, y in c]
cstart.append(len(pts))
out.append(f"  TG_CHARS = '{CHARS}';")
out.append('  TG_ADV: array[0..%d] of Integer = (%s);' % (len(adv)-1, ', '.join(map(str, adv))))
out.append('  TG_GFIRST: array[0..%d] of Integer = (%s);' % (len(gfirst)-1, ', '.join(map(str, gfirst))))
out.append('  TG_GCOUNT: array[0..%d] of Integer = (%s);' % (len(gcount)-1, ', '.join(map(str, gcount))))
out.append('  TG_CSTART: array[0..%d] of Integer = (%s);' % (len(cstart)-1, ', '.join(map(str, cstart))))
rows = [', '.join('%g, %g' % p for p in pts[i:i+6]) for i in range(0, len(pts), 6)]
out.append('  TG_PTS: array[0..%d] of Single = (\n    %s);' % (2*len(pts)-1, ',\n    '.join(rows)))
open(os.path.join(HERE, '..', '..', 'src', 'titleglyphs.inc'), 'w').write('\n'.join(out) + '\n')
print('glyphs', CHARS, 'points', len(pts), 'contours', len(cstart)-1, 'xh', xh, 'upm', upm)
